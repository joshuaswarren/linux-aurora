"""Derive the MTP / DockChannel device-tree values of one Apple board from its decoded ADT.

The ADT is the DeviceTree.<board>.im4p member of a macOS IPSW (or the machine's own dump), decoded to raw
ADT bytes; m1n1's python package (m1n1/adt.py) parses it.  Nothing from the ADT is stored in the tree: the
tool prints numbers (addresses, interrupt numbers, stream id, interface list) that the device-tree files hold.

  mtp_dt_from_adt.py --m1n1 DIR ADT                     print the derived values as JSON
  mtp_dt_from_adt.py --m1n1 DIR ADT --render BOARD      print t6050-BOARD-peripherals.dtsi

DIR is the directory that contains the m1n1 python package.  The same derivation on the J813 ADT gives the
values in t8142-j813-peripherals.dtsi (tools/asahi/mtp-dt-from-adt-tests.py).

SRAM window: the ADT does not carry the MTP SRAM base.  The ASC window starts at A, the firmware SRAM at
A + SRAM_OFFSET.  J813 (T8142) uses 0x600000; M3 boards use 0x800000.  T6050 is assumed to follow J813.
"""
import argparse
import json
import sys

SRAM_OFFSET = 0x600000
SRAM_SIZE = 0x100000
ASC_SIZE = 0x4000          # control window used by the helper driver; the ADT window is larger
DOCK_IRQ_REG = 1           # ADT dockchannel-mtp reg[1]: the interrupt window
DOCK_RANGE_FIRST = 4       # reg[4] starts the child window range
DOCK_RANGE_SIZE = 0x20000
# child windows inside that range, as ADT reg index -> offset from reg[4]
DOCK_CHILDREN = ((4, 0x0), (5, 0x4000), (2, 0x8000), (3, 0xC000))


def load(adt_path, m1n1):
    sys.path.insert(0, m1n1)
    sys.dont_write_bytecode = True
    from m1n1.adt import load_adt
    with open(adt_path, "rb") as f:
        return load_adt(f.read())


def derive(adt):
    mtp = adt["/arm-io/mtp"]
    dart = adt["/arm-io/dart-mtp"]
    dock = adt["/arm-io/dockchannel-mtp"]
    transport = dock["mtp-transport"]
    asc, asc_size = mtp.get_reg(0)
    # the ADT lists the mailbox interrupts as send-not-empty, send-empty, recv-not-empty, recv-empty
    sne, se, rne, re_ = list(mtp.interrupts)
    dart_reg, dart_size = dart.get_reg(0)
    dock_regs = [dock.get_reg(i) for i in range(6)]
    first = dock_regs[DOCK_RANGE_FIRST][0]
    return {
        "asc": [asc, ASC_SIZE], "asc_adt_size": asc_size,
        "sram": [asc + SRAM_OFFSET, SRAM_SIZE],
        "mailbox": [asc + 0x8000, 0x4000],
        "mailbox_irqs": {"send-empty": se, "send-not-empty": sne, "recv-empty": re_, "recv-not-empty": rne},
        "dart": [dart_reg, dart_size], "dart_irq": list(dart.interrupts)[0], "dart_sid": dart.sid,
        "dock_irq_reg": [dock_regs[DOCK_IRQ_REG][0], 0x1000], "dock_irq": list(dock.interrupts)[0],
        "dock_ranges": [first, DOCK_RANGE_SIZE],
        "fifo_size": dock.fifo_size,
        "interfaces": [c.name for c in transport],
        "multi_touch_personality": transport["multi-touch"].hid_merge_personality,
        "mtp_gates_listed": bool(mtp.power_gates or mtp.clock_gates or getattr(dart, "power_gates", None)
                                 or getattr(dart, "clock_gates", None)),
        "adt_checks": {
            "dock_child_windows_follow_the_range": all(
                dock_regs[i][0] == first + off for i, off in DOCK_CHILDREN),
            "board": adt.compatible[0],
        },
    }


def cells(a):
    return "%d 0x%08x" % (a >> 32, a & 0xFFFFFFFF)


def render(v, board):
    ids = v["mailbox_irqs"]
    irq = lambda n: "<AIC_IRQ %d IRQ_TYPE_LEVEL_HIGH>" % n
    reg = lambda r: "<%s 0 0x%x>" % (cells(r[0]), r[1])
    base = v["asc"][0]
    return f"""// SPDX-License-Identifier: GPL-2.0+ OR MIT
/*
 * T6050 {board}: built-in keyboard and trackpad, MTP over DockChannel.
 * Generated by tools/asahi/mtp_dt_from_adt.py from an ADT of this board; the same
 * derivation reproduces the J813 nodes. The SRAM window (asc + 0x600000) is not
 * in the ADT; it is the J813 offset. The MTP ASC and DART carry no power or clock
 * gates in the ADT, so no power-domains are listed: the boot firmware keeps the
 * block powered, as on J813.
 * The trackpad firmware is the user's own (apple/tpmtfw-{board}.bin); none is shipped.
 * Power method 2 with firmware-owned reset follows J813, the same MTP generation.
 */
#include <dt-bindings/interrupt-controller/apple-aic.h>
#include <dt-bindings/interrupt-controller/irq.h>

/ {{
	aliases {{
		mtp = &mtp;
		keyboard = &keyboard;
	}};
}};

&{{/soc}} {{
	mtp: mtp@{base:x} {{
		compatible = "apple,t6050-mtp", "apple,t6050-rtk-helper-asc4",
			     "apple,mtp", "apple,rtk-helper-asc4";
		/* The second region is firmware SRAM, not the ASC control window. */
		reg = {reg(v["asc"])},
		      {reg(v["sram"])};
		reg-names = "asc", "sram";
		mboxes = <&mtp_mbox>;
		iommus = <&mtp_dart {v["dart_sid"]}>;
	}};

	mtp_mbox: mailbox@{v["mailbox"][0]:x} {{
		compatible = "apple,t6050-asc-mailbox", "apple,asc-mailbox-v4";
		reg = {reg(v["mailbox"])};
		interrupts = {irq(ids["send-empty"])},
			     {irq(ids["send-not-empty"])},
			     {irq(ids["recv-empty"])},
			     {irq(ids["recv-not-empty"])};
		interrupt-names = "send-empty", "send-not-empty", "recv-empty", "recv-not-empty";
		#mbox-cells = <0>;
	}};

	mtp_dart: iommu@{v["dart"][0]:x} {{
		compatible = "apple,t6050-dart", "apple,t8110-dart";
		reg = {reg(v["dart"])};
		interrupts = {irq(v["dart_irq"])};
		#iommu-cells = <1>;
		/* Keep host allocations clear of firmware's low IOVA mappings. */
		apple,dma-range = <0 0x02000000 0 0x10000000>;
	}};

	mtp_dockchannel: fifo@{v["dock_irq_reg"][0]:x} {{
		compatible = "apple,t6050-dockchannel", "apple,dockchannel";
		reg = {reg(v["dock_irq_reg"])};
		reg-names = "irq";
		interrupts = {irq(v["dock_irq"])};
		ranges = <0 {cells(v["dock_ranges"][0])} 0x{v["dock_ranges"][1]:x}>;
		nonposted-mmio;
		#address-cells = <1>;
		#size-cells = <1>;
		interrupt-controller;
		#interrupt-cells = <2>;

		mtp_hid: input@8000 {{
			compatible = "apple,dockchannel-hid";
			reg = <0x8000 0x1000>, <0xc000 0x1000>,
			      <0x0000 0x1000>, <0x4000 0x1000>;
			reg-names = "config", "data", "rmt-config", "rmt-data";
			iommus = <&mtp_dart {v["dart_sid"]}>;
			interrupt-parent = <&mtp_dockchannel>;
			interrupts = <2 IRQ_TYPE_LEVEL_HIGH>, <3 IRQ_TYPE_LEVEL_HIGH>;
			interrupt-names = "tx", "rx";
			apple,fifo-size = <0x{v["fifo_size"]:x}>;
			apple,helper-cpu = <&mtp>;

			stm {{ }};

			multi-touch {{
				firmware-name = "apple/tpmtfw-{board}.bin";
				apple,power-method = <2>;
				apple,firmware-managed-reset;
			}};

			/* Layout is filled by the loader using this machine's own data. */
			keyboard: keyboard {{ }};
		}};
	}};
}};
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("adt")
    ap.add_argument("--m1n1", required=True, help="directory that contains the m1n1 python package (m1n1/adt.py)")
    ap.add_argument("--render", metavar="BOARD", help="print the T6050 peripherals dtsi for BOARD, e.g. j714c")
    a = ap.parse_args()
    v = derive(load(a.adt, a.m1n1))
    if a.render:
        sys.stdout.write(render(v, a.render))
    else:
        json.dump(v, sys.stdout, indent=1, sort_keys=True, default=str)
        print()


if __name__ == "__main__":
    main()
